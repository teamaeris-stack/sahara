export const translations = { en, hi } as const;
export type TKey = keyof typeof en;

interface LangContextValue {
  /** Selected language; "en" until hydration or setup completes. */
  lang: Lang;
  /** True once localStorage has been read on the client. */
  ready: boolean;
  /** True when no language has ever been chosen on this device. */
  needsSetup: boolean;
  setLang: (lang: Lang) => void;
  t: (key: TKey) => string;
  tx: (value: L) => string;
}

const LangContext = createContext<LangContextValue | null>(null);

function readLang(): Lang | null {
  try {
    const v = localStorage.getItem(LANGUAGE_KEY);
    return v === "en" || v === "hi" ? v : null;
  } catch {
    return null;
  }
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [stored, setStored] = useState<Lang | null>(null);
  const [ready, setReady] = useState(false);

  useEffect(() => {
    setStored(readLang());
    setReady(true);
  }, []);

  const lang: Lang = stored ?? "en";

  useEffect(() => {
    if (ready) document.documentElement.lang = lang === "hi" ? "hi" : "en";
  }, [lang, ready]);

  const setLang = useCallback((next: Lang) => {
    setStored(next);
    try {
      localStorage.setItem(LANGUAGE_KEY, next);
    } catch {
      /* ignore */
    }
  }, []);

  const value = useMemo<LangContextValue>(
    () => ({
      lang,
      ready,
      needsSetup: ready && stored === null,
      setLang,
      t: (key) => translations[lang][key],
      tx: (v) => (lang === "hi" ? v.hi : v.en),
    }),
    [lang, ready, stored, setLang],
  );

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useLang() {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error("useLang must be used inside LanguageProvider");
  return ctx;
}
